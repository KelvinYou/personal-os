#!/usr/bin/env python3
"""Export the Python wealth report serialization contract for the web dashboard."""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from lib.wealth.report_models import WealthReport  # noqa: E402

SCHEMA_PATH = ROOT / "web" / "lib" / "report.schema.json"
TYPE_PATH = ROOT / "web" / "lib" / "report.gen.ts"
JSON2TS = ROOT / "web" / "node_modules" / ".bin" / "json2ts"


def generate() -> tuple[str, str]:
    schema = WealthReport.model_json_schema(mode="serialization")
    schema_text = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
    if not JSON2TS.is_file():
        raise RuntimeError("json-schema-to-typescript missing; run cd web && npm ci")
    result = subprocess.run([str(JSON2TS), "--no-additionalProperties"],
                            input=schema_text, text=True, capture_output=True,
                            cwd=ROOT / "web", check=True)
    type_text = "// Generated by scripts/export_wealth_report_schema.py. Do not edit.\n" + result.stdout
    return schema_text, type_text


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if committed outputs have drifted")
    args = parser.parse_args()
    schema_text, type_text = generate()
    outputs = ((SCHEMA_PATH, schema_text), (TYPE_PATH, type_text))
    if args.check:
        drifted = [str(path.relative_to(ROOT)) for path, content in outputs
                   if not path.is_file() or path.read_text(encoding="utf-8") != content]
        if drifted:
            print("[Status: Critical] stale generated report contract: " + ", ".join(drifted))
            return 1
        print("[Status: OK] generated wealth report contract is current")
        return 0
    for path, content in outputs:
        path.write_text(content, encoding="utf-8")
        print(f"[Status: OK] wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
