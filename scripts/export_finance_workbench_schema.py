#!/usr/bin/env python3
"""Generate the separate Python-owned workbench snapshot contract."""
import argparse
import json
import subprocess
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from lib.wealth.workbench import WorkbenchSnapshot


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = json.dumps(WorkbenchSnapshot.model_json_schema(mode="serialization"), indent=2) + "\n"
    result = subprocess.run([str(ROOT / "web/node_modules/.bin/json2ts"), "--no-additionalProperties"], input=schema, text=True, capture_output=True, check=True, cwd=ROOT / "web")
    outputs = {ROOT / "web/lib/finance-workbench.schema.json": schema, ROOT / "web/lib/finance-workbench.gen.ts": "// Generated by scripts/export_finance_workbench_schema.py. Do not edit.\n" + result.stdout}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                print("[Status: Critical] Regenerate with scripts/export_finance_workbench_schema.py")
                return 1
        else:
            path.write_text(content)
    print("[Status: OK] Finance workbench contract is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
